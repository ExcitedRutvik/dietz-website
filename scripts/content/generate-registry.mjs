// Regenerates src/content/pages/index.ts from whatever content files exist on
// disk. Content files are authored one-per-page-per-locale; this keeps the
// aggregator from being a merge-conflict hotspot when several people (or
// agents) add pages at once. Re-run after adding content:
//   node scripts/content/generate-registry.mjs
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, relative } from "node:path";

const ROOT = "src/content/pages";

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) return walk(p);
    return p.endsWith(".ts") && name !== "index.ts" ? [p] : [];
  });
}

const files = walk(ROOT).sort();
const entries = files.map((file) => {
  const src = readFileSync(file, "utf8");
  const exp = src.match(/export const ([A-Za-z0-9_]+)/)?.[1];
  const id = src.match(/id:\s*"([^"]+)"/)?.[1];
  const locale = src.match(/locale:\s*"([a-z]{2})"/)?.[1];
  if (!exp || !id || !locale) {
    throw new Error(`${file}: could not parse export/id/locale`);
  }
  const spec = "./" + relative(ROOT, file).replace(/\.ts$/, "");
  return { exp, id, locale, spec, file };
});

// Two entries claiming the same locale+slug would mean one silently shadows
// the other in the lookup map, so fail loudly here instead.
// Two entries claiming the same locale+id are just as bad: `alternates()`
// joins locales by id, so a collision makes the language switcher point at
// whichever file the glob happened to yield first. Check both keys.
const seen = new Map();
for (const e of entries) {
  const src = readFileSync(e.file, "utf8");
  const slug = src.match(/slug:\s*"([^"]*)"/)?.[1] ?? "";
  for (const key of [`slug ${e.locale}:${slug}`, `id ${e.locale}:${e.id}`]) {
    if (seen.has(key)) {
      throw new Error(`duplicate ${key}: ${seen.get(key)} and ${e.file}`);
    }
    seen.set(key, e.file);
  }
}

const imports = entries
  .map((e) => `import { ${e.exp} } from "${e.spec}";`)
  .join("\n");
const list = entries.map((e) => `  ${e.exp},`).join("\n");

writeFileSync(
  join(ROOT, "index.ts"),
  `// GENERATED by scripts/content/generate-registry.mjs — do not edit by hand.
// Re-run that script after adding or removing a content file.
//
// This file IS the canonical-ID<->slug map: every PageEntry carries \`id\`,
// \`locale\` and \`slug\` together, so there is no separate table to keep in
// sync. A locale missing from an id's group means the page does not exist in
// that locale — absence is the signal, there is no "unavailable" sentinel.
import type { Locale } from "@/lib/locale";
import type { PageEntry } from "@/content/schema";
${imports}

const ALL: PageEntry[] = [
${list}
];

const byLocaleSlug = new Map<string, PageEntry>();
const byId = new Map<string, Map<Locale, PageEntry>>();

for (const entry of ALL) {
  byLocaleSlug.set(\`\${entry.locale}:\${entry.slug}\`, entry);
  if (!byId.has(entry.id)) byId.set(entry.id, new Map());
  byId.get(entry.id)!.set(entry.locale, entry);
}

export function getPage(locale: Locale, slugParts: string[]): PageEntry | undefined {
  return byLocaleSlug.get(\`\${locale}:\${slugParts.join("/")}\`);
}

/** The full entry for a canonical id in one locale — used by nav rendering,
 * which needs both the href (via slug) and a label (via seo.navLabel/title). */
export function getPageById(id: string, locale: Locale): PageEntry | undefined {
  return byId.get(id)?.get(locale);
}

/** Every locale a canonical page id exists in, mapped to that locale's slug. */
export function alternates(id: string): Partial<Record<Locale, string>> {
  const m = byId.get(id);
  if (!m) return {};
  const out: Partial<Record<Locale, string>> = {};
  for (const [locale, entry] of m) out[locale] = entry.slug;
  return out;
}

/** Static params for the generic [...slug] dispatcher, one locale at a time.
 * Excludes homepages (slug === ""), which have their own route. */
export function routeParamsFor(locale: Locale): { slug: string[] }[] {
  return ALL.filter((e) => e.locale === locale && e.slug !== "").map((e) => ({
    slug: e.slug.split("/"),
  }));
}

/** Locales that have a homepage entry at all — drives [locale]/page.tsx's
 * generateStaticParams instead of a hardcoded list. */
export function homepageLocales(): Locale[] {
  return [...new Set(ALL.filter((e) => e.type === "homepage").map((e) => e.locale))];
}

/** Every registered page, for sitemap generation. */
export function allEntries(): readonly PageEntry[] {
  return ALL;
}
`,
);

console.log(`registry: ${entries.length} entries from ${files.length} files`);
